// T3 Code color roles. Dark roles map palette.json. Values that are not in the
// palette (blends and tints) and the light variant stay explicit.
export type Palette = { [key: string]: string | { [key: string]: string } };

export function darkRoles(palette: Palette): Record<string, string> {
  const p = palette as Record<string, string> & { syntax: Record<string, string> };
  return {
    canvas: p.canvas,
    chrome: p.canvas,
    toolbar: p.canvas,
    toolbarForeground: p.text,
    toolbarBorder: p.border,
    toolbarControl: p.canvasRaised,
    toolbarControlForeground: p.text,
    toolbarControlHover: "#2a3a3c",
    surface: p.canvasRaised,
    surfaceRaised: "#282c2d",
    surfaceOverlay: p.canvasOverlay,
    text: p.text,
    textMuted: p.textMuted,
    border: p.border,
    input: "#282c2d",
    focus: p.accent,
    accent: p.accent,
    accentForeground: p.onAccent,
    secondary: "#282c2d",
    secondaryForeground: p.text,
    muted: "#282c2d",
    mutedForeground: p.warm,
    placeholder: p.warm,
    secondaryLabel: p.warm,
    iconMuted: p.textMuted,
    error: p.error,
    errorForeground: p.syntax.variable,
    errorSurface: "#3a2424",
    warning: p.warning,
    warningForeground: p.syntax.string,
    warningSurface: "#3a3424",
    update: p.accent,
    updateForeground: p.accentHover,
    updateSurface: "#2a3a3c",
    accentSurface: "#2a3a3c",
    accentSurfaceForeground: p.text,
    messageSurface: "#262a2b",
    messageForeground: p.text,
    messageAction: p.accent,
    messageActionForeground: p.onAccent,
    messageActionHover: p.accentHover,
    codeBackground: p.canvas,
    codeForeground: p.text,
    searchMatchBackground: "#5c4f2a",
    searchMatchForeground: p.text,
    searchMatchActiveBackground: p.warning,
    searchMatchActiveForeground: p.onAccent,
    sidebar: p.canvasOverlay,
    sidebarForeground: p.text,
    sidebarMutedForeground: p.warm,
    sidebarControlSurface: p.canvasRaised,
    sidebarRowHover: "#282c2d",
    sidebarRowActive: "#2a3a3c",
    sidebarRowSelected: "#2a3a3c",
    sidebarBorder: p.border,
    terminalBackground: p.canvas,
    terminalForeground: p.text,
    terminalCursor: p.accent,
    terminalSelection: p.selection,
    terminalScrollbar: p.border,
    terminalScrollbarHover: p.accent,
  };
}

